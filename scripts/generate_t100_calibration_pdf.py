doc = fitz.open()
for title, body in CHAPTERS:
    page = doc.new_page(width=595, height=842)
    # 写入书签
    page.insert_text(
        (50, 50),
        title.replace("# ", ""),
        fontsize=16,
        fontname="china-s",
        color=(0, 0, 0),
    )
    # 正文首行必须是 # 标题（供 OutlineTree.split 切章 + 页码注入）
    full_text = title + "\n\n" + body
